#!/usr/bin/env python3
"""Regenerate data/intensity.js from Ember's yearly electricity data.

Usage:
    python3 tools/update_intensity.py                # download the latest release
    python3 tools/update_intensity.py path/to.csv    # use a local copy

Source: https://ember-energy.org/data/yearly-electricity-data/ (CC-BY-4.0)
For each country we keep the most recent year with a CO2 intensity value.
"""
import csv
import io
import json
import re
import sys
import urllib.request
from datetime import date
from pathlib import Path

URL = ("https://storage.googleapis.com/emb-prod-bkt-publicdata/"
       "public-downloads/yearly_full_release_long_format.csv")
OLDEST_YEAR = 2022  # skip countries whose data is too old
RENAMES = {
    "Congo (the Democratic Republic of the)": "DR Congo",
    "Korea (the Democratic People's Republic of)": "North Korea",
    "Lao People's Democratic Republic (the)": "Laos",
    "Falkland Islands (the) [Malvinas]": "Falkland Islands",
    "Palestine, State of": "Palestine",
    "Tanzania, the United Republic of": "Tanzania",
    "Iran (Islamic Republic of)": "Iran",
    "Venezuela (Bolivarian Republic of)": "Venezuela",
    "Russian Federation (the)": "Russia",
    "Syrian Arab Republic (the)": "Syria",
    "Bosnia Herzegovina": "Bosnia and Herzegovina",
    "Viet Nam": "Vietnam",
    "Turkey": "Türkiye",
    "United States of America": "United States",
}


def pretty(name):
    return RENAMES.get(name) or re.sub(r" \(the\)$", "", name)


OUT = Path(__file__).resolve().parent.parent / "data" / "intensity.js"


def rows(path):
    if path:
        with open(path, newline="", encoding="utf-8") as f:
            yield from csv.DictReader(f)
    else:
        with urllib.request.urlopen(URL) as r:
            yield from csv.DictReader(io.TextIOWrapper(r, encoding="utf-8"))


def main():
    latest = {}
    for r in rows(sys.argv[1] if len(sys.argv) > 1 else None):
        if r["Variable"] != "CO2 intensity" or not r["Value"]:
            continue
        if r["Area type"] != "Country or economy" and r["Area"] not in ("World", "EU"):
            continue
        year = int(r["Year"])
        if r["Area"] not in latest or year > latest[r["Area"]]["year"]:
            latest[r["Area"]] = {"name": pretty(r["Area"]), "iso": r["ISO 3 code"] or r["Area"].upper(),
                                 "year": year, "g": round(float(r["Value"]))}

    special = [latest.pop("World"), latest.pop("EU")]
    special[1]["name"] = "European Union"
    countries = sorted((c for c in latest.values() if c["year"] >= OLDEST_YEAR),
                       key=lambda c: c["name"])
    data = {"updated": date.today().isoformat(), "regions": special, "countries": countries}
    OUT.write_text(
        "// Generated by tools/update_intensity.py from Ember yearly electricity data (CC-BY-4.0).\n"
        "// Carbon intensity of electricity generation in gCO2/kWh, most recent year per country.\n"
        "window.INTENSITY = " + json.dumps(data, ensure_ascii=False, separators=(",", ":"))
        .replace('},{', '},\n{') + ";\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(countries)} countries)")


if __name__ == "__main__":
    main()
